#!/usr/bin/env python3
"""Generates JapaneseTransforms.kt from the JSON produced by dump.mjs.

Usage:
  ./regenerate.sh   (downloads Yomitan sources, dumps rules, writes the Kotlin file)
"""
import json
import sys

def kstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'

data = json.load(open(sys.argv[1], encoding='utf-8'))
out = []
w = out.append
w('// GENERATED by tools/yomitan-transforms — do not edit by hand.')
w('//')
w('// Rules ported from Yomitan ext/js/language/ja/japanese-transforms.js')
w('// Copyright (C) 2024-2026 Yomitan Authors. Licensed under the GNU General Public License v3.0 or later.')
w('package dev.jibiki.japanese')
w('')
w('internal object JapaneseTransforms {')
w('    val conditions: List<ConditionDef> = listOf(')
for name, c in data['conditions'].items():
    sub = 'null' if c['sub'] is None else 'listOf(' + ', '.join(kstr(x) for x in c['sub']) + ')'
    w(f'        ConditionDef({kstr(name)}, isDictionaryForm = {"true" if c["isDictionaryForm"] else "false"}, subConditions = {sub}),')
w('    )')
w('')
w('    val transforms: List<TransformDef> by lazy {')
w('        listOf(' + ', '.join(f't{i}()' for i in range(len(data['transforms']))) + ')')
w('    }')
for i, t in enumerate(data['transforms']):
    w('')
    w(f'    private fun t{i}() = TransformDef(')
    w(f'        {kstr(t["name"])},')
    w('        listOf(')
    for r in t['rules']:
        kind = 'S' if r['type'] == 'suffix' else 'W'
        w(f'            r(\'{kind}\', {kstr(r["in"])}, {kstr(r["out"])}, {kstr(" ".join(r["ci"]))}, {kstr(" ".join(r["co"]))}),')
    w('        ),')
    w('    )')
w('')
w('    private fun r(kind: Char, inflected: String, deinflected: String, conditionsIn: String, conditionsOut: String) =')
w('        RuleDef(')
w('            wholeWord = kind == \'W\',')
w('            inflected = inflected,')
w('            deinflected = deinflected,')
w('            conditionsIn = conditionsIn.split(\' \').filter { it.isNotEmpty() },')
w('            conditionsOut = conditionsOut.split(\' \').filter { it.isNotEmpty() },')
w('        )')
w('}')
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
